from dataclasses import dataclass, field

from lerobot.configs.policies import PreTrainedConfig
from lerobot.configs.types import NormalizationMode
from lerobot.optim.optimizers import AdamWConfig


@PreTrainedConfig.register_subclass("cortex_agv")
@dataclass
class CortexAGVConfig(PreTrainedConfig):
    """Configuration class for the Action Chunking Transformers policy.

    [...original docstring unchanged...]

    Added (Method 1 — action discretization for long-tail action distributions):
        discretize_actions: If True, the action head outputs a categorical
            distribution over `n_action_bins` per action dimension per timestep,
            and the loss is class-weighted cross-entropy instead of L1. Designed
            for datasets where most actions cluster at zero with rare extreme
            values (e.g. driving, where 90% of steering commands are zero).
        n_action_bins: Number of categorical buckets per action dimension.
        action_bins_path: Path to a .pt file produced by `compute_action_bins.py`
            containing bin centers (in normalized space) and per-bin class
            weights. Required when `discretize_actions=True`.
    """

    # Input / output structure.
    n_obs_steps: int = 1
    chunk_size: int = 100
    n_action_steps: int = 100

    normalization_mapping: dict[str, NormalizationMode] = field(
        default_factory=lambda: {
            "VISUAL": NormalizationMode.MEAN_STD,
            "STATE": NormalizationMode.MEAN_STD,
            "ACTION": NormalizationMode.MEAN_STD,
        }
    )

    # Architecture.
    # Vision backbone.
    vision_backbone: str = "resnet18"
    pretrained_backbone_weights: str | None = "ResNet18_Weights.IMAGENET1K_V1"
    replace_final_stride_with_dilation: int = False
    # Transformer layers.
    pre_norm: bool = False
    dim_model: int = 512
    n_heads: int = 8
    dim_feedforward: int = 3200
    feedforward_activation: str = "relu"
    n_encoder_layers: int = 4
    # Note: Although the original ACT implementation has 7 for `n_decoder_layers`, there is a bug in the code
    # that means only the first layer is used. Here we match the original implementation by setting this to 1.
    # See this issue https://github.com/tonyzhaozh/act/issues/25#issue-2258740521.
    n_decoder_layers: int = 1
    # VAE.
    use_vae: bool = True
    latent_dim: int = 32
    n_vae_encoder_layers: int = 4

    # Inference.
    # Note: the value used in ACT when temporal ensembling is enabled is 0.01.
    temporal_ensemble_coeff: float | None = None

    # Training and loss computation.
    dropout: float = 0.1
    kl_weight: float = 10.0

    # Training preset
    optimizer_lr: float = 1e-5
    optimizer_weight_decay: float = 1e-4
    optimizer_lr_backbone: float = 1e-5

    # ── Action discretization (Method 1: fix for long-tail / mode-collapse) ──
    # Default OFF so existing checkpoints / configs keep working unchanged.
    # Enable by setting discretize_actions=true AND pointing action_bins_path
    # at a file generated by compute_action_bins.py.
    discretize_actions: bool = True
    n_action_bins: int = 31
    action_bins_path: str | None = "C:/Users/Aadi/aditya/agvdata-noyolo_bins_uniform_a01.pt"

    def __post_init__(self):
        super().__post_init__()

        """Input validation (not exhaustive)."""
        if not self.vision_backbone.startswith("resnet"):
            raise ValueError(
                f"`vision_backbone` must be one of the ResNet variants. Got {self.vision_backbone}."
            )
        if self.temporal_ensemble_coeff is not None and self.n_action_steps > 1:
            raise NotImplementedError(
                "`n_action_steps` must be 1 when using temporal ensembling. This is "
                "because the policy needs to be queried every step to compute the ensembled action."
            )
        if self.n_action_steps > self.chunk_size:
            raise ValueError(
                f"The chunk size is the upper bound for the number of action steps per model invocation. Got "
                f"{self.n_action_steps} for `n_action_steps` and {self.chunk_size} for `chunk_size`."
            )
        if self.n_obs_steps != 1:
            raise ValueError(
                f"Multiple observation steps not handled yet. Got `nobs_steps={self.n_obs_steps}`"
            )

        # Discretization validation
        if self.discretize_actions:
            if self.action_bins_path is None:
                raise ValueError(
                    "`discretize_actions=True` requires `action_bins_path` to point "
                    "to a .pt file produced by `compute_action_bins.py`."
                )
            if self.n_action_bins < 2:
                raise ValueError(
                    f"`n_action_bins` must be >= 2 when discretize_actions=True. "
                    f"Got {self.n_action_bins}."
                )

    def get_optimizer_preset(self) -> AdamWConfig:
        return AdamWConfig(
            lr=self.optimizer_lr,
            weight_decay=self.optimizer_weight_decay,
        )

    def get_scheduler_preset(self) -> None:
        return None

    def validate_features(self) -> None:
        if not self.image_features and not self.env_state_feature:
            raise ValueError("You must provide at least one image or the environment state among the inputs.")

    @property
    def observation_delta_indices(self) -> None:
        return None

    @property
    def action_delta_indices(self) -> list:
        return list(range(self.chunk_size))

    @property
    def reward_delta_indices(self) -> None:
        return None